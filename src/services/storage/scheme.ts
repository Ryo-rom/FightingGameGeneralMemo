export const INIT_DB = `
PRAGMA journal_mode = WAL;
CREATE TABLE IF NOT EXISTS button(
    bid INTEGER PRIMARY KEY AUTOINCREMENT
  , bName TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS buttonPreset(
    pid INTEGER NOT NULL
  , idx INTEGER NOT NULL
        CHECK(idx BETWEEN 0 AND 59)
  , bid INTEGER NOT NULL
  , PRIMARY KEY(pid, idx)
);
CREATE TABLE IF NOT EXISTS buttonSet(
    chid INTEGER NOT NULL
  , bid INTEGER NOT NULL
  , idx INTEGER NOT NULL
        CHECK(idx BETWEEN 0 AND 59)
  , PRIMARY KEY(chid, bid)
  , UNIQUE(chid, idx)
);
CREATE TABLE IF NOT EXISTS character(
    chid INTEGER PRIMARY KEY AUTOINCREMENT
  , cName TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS combo(
    coid INTEGER PRIMARY KEY AUTOINCREMENT
  , combo TEXT NOT NULL
  , chid INTEGER NOT NULL
);
CREATE TABLE IF NOT EXISTS tag(
    tid INTEGER PRIMARY KEY AUTOINCREMENT
  , tName TEXT NOT NULL
  , type INTEGER NOT NULL CHECK(type IN (0, 1))
);
CREATE TABLE IF NOT EXISTS comboSet(
    coid INTEGER NOT NULL
  , tid INTEGER NOT NULL
  , value INTEGER NOT NULL
  , PRIMARY KEY(coid, tid)
);
CREATE TABLE IF NOT EXISTS presetName(
    pid INTEGER PRIMARY KEY AUTOINCREMENT
  , pName TEXT NOT NULL
);
`;
